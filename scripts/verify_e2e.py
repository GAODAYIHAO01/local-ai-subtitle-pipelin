#!/usr/bin/env python3
"""Measure and publish real end-to-end ASR evidence, never simulated results."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import platform
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

SAMPLE_URL = "https://github.com/openai/whisper/blob/main/tests/jfk.flac"


def main() -> int:
    parser = argparse.ArgumentParser(description="Verify real VAD and Whisper transcription")
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--output-dir", type=Path, default=Path("outputs"))
    parser.add_argument("--report-dir", type=Path, default=Path("evidence"))
    parser.add_argument("--model", default="tiny")
    args = parser.parse_args()
    source = args.input.resolve()
    if not source.is_file():
        parser.error(f"Audio source does not exist: {source}")
    args.output_dir.mkdir(parents=True, exist_ok=True)
    args.report_dir.mkdir(parents=True, exist_ok=True)

    command = [
        sys.executable, "-m", "subtitle_pipeline.cli", str(source),
        "--output-dir", str(args.output_dir), "--model", args.model,
        "--device", "cpu", "--compute-type", "int8", "--language", "en",
    ]
    process = subprocess.run(command, capture_output=True, text=True)
    if process.returncode:
        print("REAL ASR INFERENCE FAILED: no verified evidence", file=sys.stderr)
        print(process.stdout, file=sys.stderr)
        print(process.stderr, file=sys.stderr)
        return process.returncode

    json_path = args.output_dir / "subtitles.json"
    srt_path = args.output_dir / "subtitles.srt"
    if not json_path.is_file() or not srt_path.is_file():
        print("FAILED: missing model-produced SRT/JSON", file=sys.stderr)
        return 1
    payload = json.loads(json_path.read_text(encoding="utf-8"))
    captions = payload.get("captions", [])
    if not captions:
        print("FAILED: ASR produced no subtitles", file=sys.stderr)
        return 1
    duration = float(payload["audio_duration_seconds"])
    elapsed = float(payload["elapsed_seconds"])
    for index, item in enumerate(captions):
        if not (0 <= item["start"] < item["end"] <= duration + 0.001):
            print(f"FAILED: invalid caption interval #{index+1}", file=sys.stderr)
            return 1
        if index and captions[index - 1]["end"] > item["start"]:
            print(f"FAILED: overlapping caption #{index+1}", file=sys.stderr)
            return 1

    rtf = elapsed / duration
    sha256 = hashlib.sha256(source.read_bytes()).hexdigest()
    lines = [
        "REAL END-TO-END SUBTITLE TRANSCRIPTION - VERIFIED EXECUTION",
        f"Completed at UTC: {datetime.now(timezone.utc).isoformat()}",
        f"Public audio source: {SAMPLE_URL}",
        f"Source SHA256: {sha256}",
        f"Python: {sys.version.split()[0]}",
        f"Host: {platform.platform()} (CPU cores: {os.cpu_count()})",
        f"ASR model: {payload['model']} / {payload['device']} / {payload['compute_type']}",
        f"Audio duration: {duration:.3f} seconds",
        f"Wall time: {elapsed:.3f} seconds (including model setup and output export)",
        f"RTF (elapsed/audio): {rtf:.3f}",
        f"VAD speech intervals: {payload['speech_intervals']}",
        f"Caption count: {len(captions)}",
        "Transcript with absolute source timestamps (first 8):",
    ]
    for c in captions[:8]:
        lines.append(f"  [{c['start']:.3f}s - {c['end']:.3f}s] {c['text']}")
    lines.extend(["", "CLI standard output:", process.stdout.strip(), "RESULT: SUCCESS"])
    log = "\n".join(lines) + "\n"
    (args.report_dir / "verification.log").write_text(log, encoding="utf-8")
    shutil.copyfile(srt_path, args.report_dir / "subtitles.srt")
    shutil.copyfile(json_path, args.report_dir / "subtitles.json")
    markdown = [
        "# Actual audio ASR verification", "",
        "**Provenance:** Generated by the public GitHub Actions workflow after the model produced real SRT/JSON output. Not a simulated log.",
        "", f"**Audio source:** {SAMPLE_URL}", f"**SHA256:** {sha256}",
        "", f"**Model:** {payload['model']} (CPU INT8)",
        f"**Wall time:** {elapsed:.3f} sec; **audio:** {duration:.3f} sec; **RTF:** {rtf:.3f}.",
        "", f"**Captions:** {len(captions)}",
        "", "This is a short real-audio smoke test, not a completed 5-10 minute milestone or a quality benchmark.",
        "", "## Actual output", "", "~~~text", log.rstrip(), "~~~",
        "", "## Artifacts", "", "- subtitles.srt - generated SRT",
        "- subtitles.json - generated JSON with execution metadata",
    ]
    (args.report_dir / "verification.md").write_text("\n".join(markdown) + "\n", encoding="utf-8")
    print(log, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
